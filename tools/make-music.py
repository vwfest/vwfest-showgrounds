#!/usr/bin/env python3
"""Synthesises the house-playlist tracks for the DJ booth. Everything is generated from scratch by this script (no samples, no third-party music),
so the tracks are original and released under CC0 1.0 (public domain). Needs numpy + ffmpeg.  Usage: python3 tools/make-music.py"""
import numpy as np, subprocess, os, json, sys
SR = 44100
rng = np.random.default_rng(209)
OUT = os.path.join(os.path.dirname(__file__), '..', 'docs', 'assets', 'music')
def mtof(m): return 440.0 * 2 ** ((np.asarray(m, dtype=float) - 69) / 12)
def env(n, a=0.005, d=0.1, s=0.7, r=0.05):
    a, d, r = int(a * SR), int(d * SR), int(r * SR); e = np.ones(n) * s
    a = min(a, n); e[:a] = np.linspace(0, 1, a, endpoint=False) if a else 1
    dd = min(d, max(0, n - a)); e[a:a + dd] = np.linspace(1, s, dd) if dd else e[a:a + dd]
    r = min(r, n); e[n - r:] *= np.linspace(1, 0, r) if r else 1
    return e
def saw(f, n, harm=14):
    t = np.arange(n) / SR; y = np.zeros(n)
    for k in range(1, harm + 1):
        if f * k > 9000: break
        y += np.sin(2 * np.pi * f * k * t) / k * (1 if k % 2 else 1)
    return y * 0.55
def square(f, n, duty=0.5):
    t = np.arange(n) / SR; return np.where((t * f) % 1 < duty, 1.0, -1.0) * 0.5
def tri(f, n):
    t = np.arange(n) / SR; return (2 * np.abs(2 * ((t * f) % 1) - 1) - 1) * 0.8
def sine(f, n, ph=0): t = np.arange(n) / SR; return np.sin(2 * np.pi * f * t + ph)
def lp(x, a):  # one-pole low-pass, vectorised via exponential kernel (fast enough for short notes)
    k = (1 - a) * a ** np.arange(min(len(x), 600)); return np.convolve(x, k)[:len(x)]
def hp(x): return np.concatenate([[0], np.diff(x)])
class Mix:
    def __init__(self, seconds): self.n = int(seconds * SR); self.L = np.zeros(self.n); self.R = np.zeros(self.n)
    def add(self, t, y, vol=1.0, pan=0.0):
        i = int(t * SR)
        if i >= self.n: return
        y = y[:self.n - i]; self.L[i:i + len(y)] += y * vol * (1 - max(0, pan)); self.R[i:i + len(y)] += y * vol * (1 + min(0, pan))
def kick(vol=1.0):
    n = int(0.32 * SR); t = np.arange(n) / SR; f = 45 + 110 * np.exp(-t * 28); ph = 2 * np.pi * np.cumsum(f) / SR
    return np.sin(ph) * np.exp(-t * 9) * 1.0 + np.sin(ph * 2) * np.exp(-t * 40) * 0.12
def snare(): n = int(0.22 * SR); t = np.arange(n) / SR; return (hp(rng.standard_normal(n)) * 0.5 * np.exp(-t * 18) + sine(190, n) * np.exp(-t * 25) * 0.5)
def clap(): n = int(0.25 * SR); t = np.arange(n) / SR; b = np.zeros(n); [b.__setitem__(slice(int(o * SR), n), b[int(o * SR):] + np.exp(-np.arange(n - int(o * SR)) / SR * 70)) for o in (0, 0.011, 0.022)]; return hp(rng.standard_normal(n)) * 0.5 * b * np.exp(-t * 14)
def hat(open_=False): n = int((0.2 if open_ else 0.06) * SR); t = np.arange(n) / SR; return hp(hp(rng.standard_normal(n))) * np.exp(-t * (14 if open_ else 70)) * 0.45
def chord(root, kind): return [root + i for i in {'m': (0, 3, 7), 'M': (0, 4, 7), 'm7': (0, 3, 7, 10), 'M7': (0, 4, 7, 11), '7': (0, 4, 7, 10), 'sus': (0, 5, 7)}[kind]]
def reverb(L, R, wet=0.18, sec=1.6):
    n = int(sec * SR); ir = rng.standard_normal(n) * np.exp(-np.arange(n) / SR * 3.2); ir[:int(0.02 * SR)] *= np.linspace(0, 1, int(0.02 * SR))
    m = len(L) + n; F = np.fft.rfft; I = np.fft.irfft
    wl = I(F(L, m) * F(ir, m), m)[:len(L)]; wr = I(F(R, m) * F(np.roll(ir, 777), m), m)[:len(R)]
    return L + wl * wet * 0.04, R + wr * wet * 0.04
def finish(mix, name, fade=2.5):
    L, R = reverb(mix.L, mix.R)
    for ch in (L, R):
        f = int(fade * SR); ch[-f:] *= np.linspace(1, 0, f); ch[:int(0.01 * SR)] *= np.linspace(0, 1, int(0.01 * SR))
    pk = max(np.abs(L).max(), np.abs(R).max()); L, R = L / pk * 0.89, R / pk * 0.89
    st = np.stack([L, R], 1); pcm = (np.tanh(st * 1.15) / np.tanh(1.15) * 32767).astype('<i2')
    wav = os.path.join('/tmp', name + '.wav'); import wave
    with wave.open(wav, 'wb') as w: w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(pcm.tobytes())
    os.makedirs(OUT, exist_ok=True); mp3 = os.path.join(OUT, name + '.mp3')
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', wav, '-codec:a', 'libmp3lame', '-b:a', '112k', '-id3v2_version', '3', '-metadata', 'comment=CC0 1.0 original track generated by tools/make-music.py', mp3], check=True)
    return len(L) / SR
def bar_plan(bars, sections):  # which instruments play on which bar
    plan = []
    for name, n in sections: plan += [name] * n
    return plan[:bars]

def house():
    bpm = 124; beat = 60 / bpm; bars = 48; m = Mix(bars * 4 * beat + 3)
    prog = [(57, 'm7'), (53, 'M7'), (48, 'M'), (55, '7')]
    plan = bar_plan(bars, [('intro', 4), ('groove', 8), ('full', 8), ('break', 4), ('full', 12), ('groove', 8), ('out', 4)])
    for b in range(bars):
        s = plan[b]; t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root + 12, kind)
        for q in range(4):
            if s != 'break' and not (s == 'out' and b % 2): m.add(t0 + q * beat, kick(), 0.95)
            if s in ('groove', 'full', 'out', 'break') and q in (1, 3) and s != 'break': m.add(t0 + q * beat, clap(), 0.5)
            if s != 'intro' or b >= 2: m.add(t0 + q * beat + beat / 2, hat(True), 0.33)
            for e in range(2): m.add(t0 + q * beat + e * beat / 2 + beat / 4, hat(), 0.18)
        if s in ('groove', 'full', 'out'):
            for e in range(16):  # offbeat saw bass
                if e % 4 == 2:
                    n = int(beat * 0.22 * SR); m.add(t0 + e * beat / 4, lp(saw(mtof(root - 12), n), 0.82) * env(n, 0.003, 0.08, 0.6, 0.03), 0.8)
        if s in ('full', 'break', 'groove'):
            for k, note in enumerate(ch):  # stab chords on the &s
                for pos in ((0.75, 2.5) if s != 'break' else (0, 2)):
                    n = int(beat * (0.45 if s != 'break' else 1.8) * SR); y = saw(mtof(note), n, 8) * env(n, 0.004, 0.2, 0.3, 0.1); m.add(t0 + pos * beat, lp(y, 0.6), 0.16 if s != 'break' else 0.2, pan=(k - 1) * 0.35)
        if s == 'full':
            for e in range(8):  # arp
                note = ch[(e * 3) % len(ch)] + 12; n = int(beat * 0.5 * SR); m.add(t0 + e * beat / 2, square(mtof(note), n, 0.3) * env(n, 0.002, 0.1, 0.2, 0.08), 0.1, pan=0.4 * (-1) ** e)
    return finish(m, 'dust-road-house')
def chip():
    bpm = 150; beat = 60 / bpm; bars = 56; m = Mix(bars * 4 * beat + 2)
    prog = [(60, 'M'), (67, 'M'), (69, 'm'), (65, 'M')]; plan = bar_plan(bars, [('a', 4), ('b', 12), ('c', 12), ('b', 12), ('c', 12), ('out', 4)])
    lead_pat = [0, 2, 4, 2, 4, 7, 4, 2]
    for b in range(bars):
        s = plan[b]; t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root + 12, kind)
        for q in range(16):
            t = t0 + q * beat / 4
            if q % 4 == 0 and s != 'out': m.add(t, kick() * 0.9, 0.9)
            if q % 8 == 4: m.add(t, snare(), 0.55)
            if q % 2 == 0 and s != 'a': m.add(t, hat(), 0.25)
            n = int(beat / 4 * 0.95 * SR); m.add(t, tri(mtof(root - 12 + (0 if q % 8 < 6 else 7)), n) * env(n, 0.002, 0.05, 0.8, 0.02), 0.55)
            if s in ('b', 'c', 'out'):
                note = ch[lead_pat[q % 8] % len(ch)] + (24 if s == 'c' else 12) + (0 if lead_pat[q % 8] < 5 else 0); n2 = int(beat / 4 * 0.9 * SR)
                m.add(t, square(mtof(note), n2, 0.25 if s == 'b' else 0.5) * env(n2, 0.001, 0.05, 0.6, 0.03), 0.13, pan=0.3 * (-1) ** (q // 2))
        if s == 'c':
            for k, note in enumerate(ch): n = int(4 * beat * SR); m.add(t0, square(mtof(note + 12), n, 0.125) * env(n, 0.01, 0.3, 0.4, 0.2), 0.05, pan=(k - 1) * 0.5)
    return finish(m, 'arcade-sunrise')
def lofi():
    bpm = 78; beat = 60 / bpm; bars = 32; m = Mix(bars * 4 * beat + 3)
    prog = [(62, 'm7'), (55, 'M7'), (60, 'M7'), (57, 'm7')]; plan = bar_plan(bars, [('a', 4), ('b', 12), ('c', 4), ('b', 8), ('out', 4)])
    for b in range(bars):
        s = plan[b]; t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root, kind)
        for k, note in enumerate(ch):  # rhodes-ish chord
            n = int(3.6 * beat * SR); t = np.arange(n) / SR; y = (sine(mtof(note), n) + 0.4 * sine(mtof(note) * 2, n) * np.exp(-t * 3) + 0.15 * sine(mtof(note) * 4, n) * np.exp(-t * 8)) * env(n, 0.006, 0.6, 0.35, 0.4); m.add(t0 + 0.0 + k * 0.012, y, 0.16, pan=(k - 1.5) * 0.25)
        if s != 'a':
            for q in (0, 2.5): m.add(t0 + q * beat, kick() * 0.8, 0.7)
            m.add(t0 + 1 * beat, snare(), 0.4); m.add(t0 + 3 * beat, snare(), 0.4)
            for e in range(8): m.add(t0 + e * beat / 2 + (0.07 * beat if e % 2 else 0), hat(), 0.16 + 0.05 * (e % 2))
            for q, off in ((0, 0), (1.5, 7), (2.5, 0), (3.25, 5)): n = int(beat * 0.9 * SR); m.add(t0 + q * beat, sine(mtof(root - 24 + off), n) * env(n, 0.01, 0.2, 0.7, 0.1), 0.55)
        if s in ('b', 'c'):
            sc = [0, 3, 7, 10, 12, 14]; 
            for e in range(4):
                if rng.random() < 0.75: note = root + 12 + sc[int(rng.integers(0, len(sc)))]; n = int(beat * 1.2 * SR); m.add(t0 + (e + rng.choice([0, 0.5])) * beat, tri(mtof(note), n) * env(n, 0.01, 0.4, 0.2, 0.3), 0.12, pan=0.35 * (-1) ** e)
    cr = hp(rng.standard_normal(m.n)) * 0.02 * (rng.random(m.n) > 0.9993) * 8; m.L += cr; m.R += np.roll(cr, 500)
    return finish(m, 'lowrider-lofi')
def synthwave():
    bpm = 100; beat = 60 / bpm; bars = 40; m = Mix(bars * 4 * beat + 3)
    prog = [(57, 'm'), (53, 'M'), (60, 'M'), (55, 'M')]; plan = bar_plan(bars, [('a', 4), ('b', 12), ('c', 8), ('b', 12), ('out', 4)])
    for b in range(bars):
        s = plan[b]; t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root + 12, kind)
        for q in range(4):
            m.add(t0 + q * beat, kick() * 0.9, 0.85 if s != 'out' or q == 0 else 0)
            if q in (1, 3): m.add(t0 + q * beat, snare(), 0.6); m.add(t0 + q * beat, clap(), 0.3)
        for e in range(8):
            if s != 'a': n = int(beat / 2 * 0.9 * SR); m.add(t0 + e * beat / 2, lp(saw(mtof(root - 12), n, 10), 0.8) * env(n, 0.003, 0.08, 0.6, 0.04), 0.7)
            m.add(t0 + e * beat / 2 + beat / 4, hat(), 0.2)
        for k, note in enumerate(ch):
            n = int(4 * beat * SR); g = 0.5 + 0.5 * np.sin(2 * np.pi * np.arange(n) / SR * bpm / 60 * 2 * 0.5); y = (saw(mtof(note), n, 8) + saw(mtof(note) * 1.006, n, 8)) * env(n, 0.05, 0.5, 0.6, 0.3); m.add(t0, lp(y, 0.8) * (0.6 + 0.4 * g), 0.1, pan=(k - 1) * 0.6)
        if s in ('c', 'b'):
            mel = [0, 4 if kind == 'M' else 3, 7, 12]; 
            for e in range(4):
                note = ch[0] + 12 + mel[(e + b) % 4]; n = int(beat * 0.95 * SR); m.add(t0 + e * beat, saw(mtof(note), n, 6) * env(n, 0.01, 0.2, 0.5, 0.2), 0.12 if s == 'b' else 0.18, pan=0.3 * (-1) ** e)
    return finish(m, 'neon-cruise')
def funk():
    bpm = 108; beat = 60 / bpm; bars = 36; m = Mix(bars * 4 * beat + 2)
    prog = [(52, '7'), (52, '7'), (57, 'm7'), (55, '7')]; plan = bar_plan(bars, [('a', 4), ('b', 16), ('c', 8), ('b', 4), ('out', 4)])
    bass_pat = [(0, 0), (0.75, 12), (1.5, 0), (2.25, 7), (2.75, 10), (3.5, 0)]
    for b in range(bars):
        s = plan[b]; t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root + 12, kind)
        for q, tt in enumerate((0, 1.5, 2.25)): m.add(t0 + tt * beat, kick() * 0.9, 0.9)
        m.add(t0 + 1 * beat, snare(), 0.65); m.add(t0 + 3 * beat, snare(), 0.65)
        for e in range(16): m.add(t0 + e * beat / 4, hat(e % 8 == 6), 0.2 if e % 2 else 0.3)
        for pos, off in bass_pat: n = int(beat * 0.3 * SR); m.add(t0 + pos * beat, lp(saw(mtof(root - 12 + off), n, 9), 0.75) * env(n, 0.002, 0.08, 0.4, 0.05), 0.75)
        if s != 'a':
            for pos in (0.5, 1.25, 2, 2.75, 3.5):
                for k, note in enumerate(ch): n = int(beat * 0.18 * SR); m.add(t0 + pos * beat, lp(saw(mtof(note), n, 8), 0.6) * env(n, 0.002, 0.05, 0.3, 0.04), 0.12, pan=(k - 1.5) * 0.25)
        if s == 'c':
            for e in range(4): note = root + 24 + [0, 3, 5, 7][(e + b) % 4]; n = int(beat * 0.5 * SR); m.add(t0 + (e + 0.5) * beat, square(mtof(note), n, 0.35) * env(n, 0.003, 0.15, 0.3, 0.1), 0.1, pan=0.3)
    return finish(m, 'airy-funk')
def chill():
    bpm = 90; beat = 60 / bpm; bars = 28; m = Mix(bars * 4 * beat + 4)
    prog = [(65, 'M7'), (64, 'm7'), (62, 'm7'), (67, 'sus')]
    for b in range(bars):
        t0 = b * 4 * beat; root, kind = prog[b % 4]; ch = chord(root, kind)
        for k, note in enumerate(ch):
            n = int(4.2 * beat * SR); y = (tri(mtof(note), n) + 0.5 * sine(mtof(note) * 1.003, n)) * env(n, 0.4, 0.8, 0.7, 0.8); m.add(t0, y, 0.14, pan=(k - 1.5) * 0.4)
        if b >= 2:
            m.add(t0, kick() * 0.7, 0.6); m.add(t0 + 2.5 * beat, kick() * 0.6, 0.5); m.add(t0 + 2 * beat, snare(), 0.3)
            for e in range(8): m.add(t0 + e * beat / 2, hat(), 0.14)
            n = int(beat * 3.5 * SR); m.add(t0, sine(mtof(root - 24), n) * env(n, 0.02, 0.3, 0.7, 0.3), 0.5)
        if b >= 4:
            for e in range(8):
                if rng.random() < 0.55: note = ch[int(rng.integers(0, len(ch)))] + 12 * int(rng.integers(1, 3)); n = int(beat * 1.5 * SR); m.add(t0 + e * beat / 2, sine(mtof(note), n) * env(n, 0.01, 0.4, 0.1, 0.5), 0.1, pan=float(rng.uniform(-0.6, 0.6)))
    return finish(m, 'sunset-chill')
TRACKS = [('dust-road-house', 'Dust Road House', house), ('arcade-sunrise', 'Arcade Sunrise', chip), ('lowrider-lofi', 'Lowrider Lo-Fi', lofi), ('neon-cruise', 'Neon Cruise', synthwave), ('airy-funk', 'Air-Cooled Funk', funk), ('sunset-chill', 'Sunset Chill', chill)]
